#!/usr/bin/env node
import fs from "node:fs"
import path from "node:path"
import process from "node:process"
import { createRequire } from "node:module"
import { fileURLToPath } from "node:url"

const workspaceRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
)
const require = createRequire(
  path.join(workspaceRoot, "packages/tools/package.json"),
)
const ts = require("typescript")
const sourcePath = path.join(
  workspaceRoot,
  "packages/tools/src/reader-viewport-anchor.ts",
)
const source = fs.readFileSync(sourcePath, "utf8").trim()
const runtime = renderRuntime(source)
const checkOnly = process.argv.includes("--check")
const platform = argumentValue("--platform") ?? "all"

if (!["all", "android", "desktop", "ios"].includes(platform)) {
  throw new Error(`Unsupported platform: ${platform}`)
}

const outputs = {
  android: {
    path: path.join(
      workspaceRoot,
      "my-reader-mobile/modules/readium/android/src/main/java/com/myreader/readium/reader/GeneratedReaderViewportAnchorScript.kt",
    ),
    content: renderKotlin(runtime),
  },
  desktop: {
    path: path.join(
      workspaceRoot,
      "my-reader/src/lib/readium/generatedReaderViewportAnchor.ts",
    ),
    content: renderTypeScript(source),
  },
  ios: {
    path: path.join(
      workspaceRoot,
      "my-reader-mobile/modules/readium/ios/Reader/EPUB/GeneratedReaderViewportAnchorScript.swift",
    ),
    content: renderSwift(runtime),
  },
}

const selectedPlatforms = platform === "all" ? Object.keys(outputs) : [platform]
const staleOutputs = selectedPlatforms.filter(
  (name) => !outputMatches(outputs[name]),
)

if (checkOnly) {
  if (staleOutputs.length > 0) {
    console.error(
      `Stale reader viewport anchor output: ${staleOutputs.join(", ")}`,
    )
    process.exit(1)
  }
  process.exit(0)
}

for (const name of staleOutputs) {
  const output = outputs[name]
  fs.mkdirSync(path.dirname(output.path), { recursive: true })
  fs.writeFileSync(output.path, output.content)
}

function argumentValue(name) {
  const index = process.argv.indexOf(name)
  return index === -1 ? undefined : process.argv[index + 1]
}

function outputMatches(output) {
  return (
    fs.existsSync(output.path) &&
    fs.readFileSync(output.path, "utf8") === output.content
  )
}

function renderRuntime(typeScriptSource) {
  const scriptSource = typeScriptSource.replace(/^export /gm, "")
  const result = ts.transpileModule(scriptSource, {
    compilerOptions: {
      module: ts.ModuleKind.ESNext,
      target: ts.ScriptTarget.ES2019,
    },
    fileName: sourcePath,
    reportDiagnostics: true,
  })
  const errors = (result.diagnostics ?? []).filter(
    (diagnostic) => diagnostic.category === ts.DiagnosticCategory.Error,
  )
  if (errors.length > 0) {
    throw new Error(
      errors
        .map((diagnostic) =>
          ts.flattenDiagnosticMessageText(diagnostic.messageText, "\n"),
        )
        .join("\n"),
    )
  }

  return `(function (window) {
${indent(result.outputText.trim(), 2)}
  return createReaderViewportAnchorRuntime(window);
})`
}

function renderTypeScript(typeScriptSource) {
  return `// Generated by scripts/generate-reader-viewport-anchor.mjs. Do not edit.
// Source: packages/tools/src/reader-viewport-anchor.ts

${typeScriptSource}
`
}

function renderSwift(runtimeSource) {
  assertSafeForSwiftRawString(runtimeSource)
  return `// Generated by scripts/generate-reader-viewport-anchor.mjs. Do not edit.
// Source: packages/tools/src/reader-viewport-anchor.ts

import Foundation

private let readerViewportAnchorRuntimeScript = #"""
${runtimeSource}
"""#

let captureReaderBookmarkAnchorScript = """
JSON.stringify((\\(readerViewportAnchorRuntimeScript))(window).captureReaderViewportAnchor())
"""

func readerViewportAnchorOffsetRestoreScript(
  domRangeJSON: String,
  yRatio: Double
) -> String {
  return """
JSON.stringify((\\(readerViewportAnchorRuntimeScript))(window).restoreReaderViewportAnchorOffset(\\(domRangeJSON), \\(yRatio)))
"""
}

let readerViewportLayoutStateScript = """
JSON.stringify((\\(readerViewportAnchorRuntimeScript))(window).readerViewportLayoutState())
"""

func readerBookmarkVisibilityScript(domRangeJSON: String) -> String {
  return """
JSON.stringify((\\(readerViewportAnchorRuntimeScript))(window).isReaderViewportAnchorVisible(\\(domRangeJSON)))
"""
}
`
}

function renderKotlin(runtimeSource) {
  return `// Generated by scripts/generate-reader-viewport-anchor.mjs. Do not edit.
// Source: packages/tools/src/reader-viewport-anchor.ts
package com.myreader.readium.reader

private val readerViewportAnchorRuntimeScript = """
${indent(escapeKotlinTemplate(runtimeSource), 4)}
""".trimIndent()

internal val captureReaderBookmarkAnchorScript = """
JSON.stringify(($readerViewportAnchorRuntimeScript)(window).captureReaderViewportAnchor())
""".trimIndent()

internal fun readerViewportAnchorOffsetRestoreScript(
  domRangeJson: String,
  yRatio: Double
): String = """
JSON.stringify(($readerViewportAnchorRuntimeScript)(window).restoreReaderViewportAnchorOffset($domRangeJson, $yRatio))
""".trimIndent()

internal val readerViewportLayoutStateScript = """
JSON.stringify(($readerViewportAnchorRuntimeScript)(window).readerViewportLayoutState())
""".trimIndent()

internal fun readerBookmarkVisibilityScript(domRangeJson: String): String = """
JSON.stringify(($readerViewportAnchorRuntimeScript)(window).isReaderViewportAnchorVisible($domRangeJson))
""".trimIndent()
`
}

function indent(value, spaces) {
  const prefix = " ".repeat(spaces)
  return value
    .split("\n")
    .map((line) => (line ? `${prefix}${line}` : ""))
    .join("\n")
}

function escapeKotlinTemplate(value) {
  return value.replaceAll("$", () => "${'$'}")
}

function assertSafeForSwiftRawString(value) {
  if (value.includes('"""#')) {
    throw new Error(
      "Reader viewport anchor source cannot close a Swift raw string",
    )
  }
}
