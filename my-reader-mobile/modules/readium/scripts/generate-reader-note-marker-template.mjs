#!/usr/bin/env node
import fs from "node:fs"
import path from "node:path"
import process from "node:process"
import { fileURLToPath } from "node:url"

const moduleRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
)
const workspaceRoot = path.resolve(moduleRoot, "../../..")
const templateRoot = path.join(
  workspaceRoot,
  "packages/tools/src/reader-note-marker",
)
const element = readTemplate("reader-note-marker.html")
const stylesheet = readTemplate("reader-note-marker.css")
const checkOnly = process.argv.includes("--check")
const platform = argumentValue("--platform") ?? "all"

if (!["all", "android", "ios"].includes(platform)) {
  throw new Error(`Unsupported platform: ${platform}`)
}

const outputs = {
  android: {
    path: path.join(
      moduleRoot,
      "android/src/main/java/com/myreader/readium/reader/GeneratedReaderNoteMarkerTemplate.kt",
    ),
    content: renderKotlin(element, stylesheet),
  },
  ios: {
    path: path.join(
      moduleRoot,
      "ios/Reader/EPUB/GeneratedReaderNoteMarkerTemplate.swift",
    ),
    content: renderSwift(element, stylesheet),
  },
}

const selectedPlatforms = platform === "all" ? Object.keys(outputs) : [platform]
const staleOutputs = selectedPlatforms.filter(
  (name) => !outputMatches(outputs[name]),
)

if (checkOnly) {
  if (staleOutputs.length > 0) {
    console.error(`Stale reader note marker output: ${staleOutputs.join(", ")}`)
    process.exit(1)
  }
  process.exit(0)
}

for (const name of staleOutputs) {
  const output = outputs[name]
  fs.mkdirSync(path.dirname(output.path), { recursive: true })
  fs.writeFileSync(output.path, output.content)
}

function argumentValue(name) {
  const index = process.argv.indexOf(name)
  return index === -1 ? undefined : process.argv[index + 1]
}

function outputMatches(output) {
  return (
    fs.existsSync(output.path) &&
    fs.readFileSync(output.path, "utf8") === output.content
  )
}

function readTemplate(fileName) {
  return fs.readFileSync(path.join(templateRoot, fileName), "utf8").trim()
}

function renderKotlin(html, css) {
  assertSafeForMultilineString(html, "Kotlin")
  assertSafeForMultilineString(css, "Kotlin")
  return `// Generated by scripts/generate-reader-note-marker-template.mjs. Do not edit.
// Sources:
// - packages/tools/src/reader-note-marker/reader-note-marker.html
// - packages/tools/src/reader-note-marker/reader-note-marker.css
package com.myreader.readium.reader

internal object ReaderNoteMarkerTemplateSource {
  val ELEMENT = """
${indent(html, 4)}
    """.trimIndent()

  val STYLESHEET = """
${indent(css, 4)}
    """.trimIndent()
}
`
}

function renderSwift(html, css) {
  assertSafeForMultilineString(html, "Swift")
  assertSafeForMultilineString(css, "Swift")
  return `// Generated by scripts/generate-reader-note-marker-template.mjs. Do not edit.
// Sources:
// - packages/tools/src/reader-note-marker/reader-note-marker.html
// - packages/tools/src/reader-note-marker/reader-note-marker.css

enum ReaderNoteMarkerTemplateSource {
  static let element = """
${indent(html, 4)}
  """

  static let stylesheet = """
${indent(css, 4)}
  """
}
`
}

function indent(value, spaces) {
  const prefix = " ".repeat(spaces)
  return value
    .split("\n")
    .map((line) => (line ? `${prefix}${line}` : ""))
    .join("\n")
}

function assertSafeForMultilineString(value, language) {
  if (value.includes('"""')) {
    throw new Error(
      `Reader note marker template cannot contain triple quotes (${language})`,
    )
  }
}
